export function getSareeBySku(sku: string): SareeSKU | undefined {
  return CATALOG.find((item) => item.sku.toLowerCase() === sku.toLowerCase());
}

export function getSareeBySlug(slug: string): SareeSKU | undefined {
  return CATALOG.find((item) => item.slug.toLowerCase() === slug.toLowerCase());
}

export function getSareesByCategory(category: string): SareeSKU[] {
  if (category === "all") return CATALOG;
  return CATALOG.filter((item) => item.category === category);
}
